"""Markdown for D1 (docs/battle-log.md) from the measured counts."""

from __future__ import annotations

SHOWN_TEXTS = 25  # distinct matching texts printed per search; the JSON has all of them

KIND_NOTES = {
    "hp": "Before -> after. The text never names a side; pcsa sets `side` from the unit (`hp` exact = ours, "
          "`pct` = theirs). See N9 for how well that agrees with the send-out rows.",
    "move": "User and move only. `label` is the row's category header; `priority` is set from a priority header.",
    "effectiveness": "Anonymous, except the immune form 'It doesn't affect X', which names the target.",
    "item": "The text carries no side: see the 'opposing' row of the table.",
    "ability": "The text carries no side: see the 'opposing' row of the table.",
    "overlay": "Battle-timer captions captured as rows; not log rows.",
    "trailing": "Rows that restate or annotate another row; `what` says which.",
}


def cell(value) -> str:
    text = str(value).replace("|", "\\|").replace("\n", " ")
    return f"`` {text} ``" if "`" in text else f"`{text}`"


def table(header: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out + [""]


def pct(part: int, whole: int) -> str:
    return f"{100 * part / whole:.1f}%" if whole else "-"


def head(data: dict) -> list[str]:
    t = data["totals"]
    missing = ", ".join(t["battles_without_log"]) or "none"
    return [
        "# What the game's battle log shows",
        "",
        "Generated by `tools/catalog/battle_log.py`; do not edit by hand. Counts: "
        "`output/catalog/battle_log.json`. Regenerate from the repo root (PowerShell):",
        "",
        "```",
        data["command"],
        "```",
        "",
        "Every row of every recorded `output/runs/*/battle-*/log.jsonl` is parsed with the row parser "
        "(`pcsa.battle.log_rows.rows_from_texts` + `parse_row`). Each row yields exactly one event kind, so "
        "every row is in exactly one section below or in the unknown bucket.",
        "",
        "Read the counts with care:",
        "- Rows are OCR text of the game's log screen, merged per turn. They are the *final* rows of each "
        "battle.",
        "- A count of 0 means 0 in these recorded OCR rows, not that the game can never show it.",
        "- Field presence is what the parser extracts, not everything a human could read from the text.",
        "",
        "## Totals",
        "",
        *table(["", "count"], [
            ["runs with a log", t["runs"]], ["battle folders", t["battle_dirs"]],
            ["battles with `log.jsonl`", t["battles"]], ["rows", t["rows"]],
            ["turns (battle, turn pairs)", t["turns"]], ["longest battle, turns", t["max_turn"]],
            ["most rows in one battle", t["rows_per_battle_max"]], ["row kinds (incl. overlay and unknown)", t["kinds"]],
        ]),
        f"Battle folders without `log.jsonl`: {missing}.",
        "",
    ]


def kinds_summary(data: dict) -> list[str]:
    rows = [[f"[{k}](#kind-{k})", v["rows"], v["battles"], v["distinct_texts"], cell(v["example"])]
            for k, v in data["kinds"].items()]
    return ["## Row kinds", "", *table(["kind", "rows", "battles", "distinct texts", "most common text"], rows)]


def kind_section(kind: str, v: dict) -> list[str]:
    out = [f'<a id="kind-{kind}"></a>', f"### {kind}", "",
           f"{v['rows']} rows in {v['battles']} battles. Example: {cell(v['example'])}", ""]
    if kind in KIND_NOTES:
        out += [KIND_NOTES[kind], ""]
    out += table(["field", "% of rows present"], [[f"`{f}`", f"{p}%"] for f, p in v["fields"].items()])
    for key, values in v["subtypes"].items():
        out += [f"Sub-types by `{key}` ({len(values)}):", ""]
        out += table(["value", "rows"], [[cell(val), n] for val, n in values.items()])
    if v.get("moves"):
        top = ", ".join(f"{m} {n}" for m, n in list(v["moves"].items())[:15])
        out += [f"{len(v['moves'])} distinct move names; most used: {top}. Full list in the JSON.", ""]
    return out


def unknown_section(data: dict) -> list[str]:
    rows = data["unknown_rows"]
    out = ["## Unknown bucket", "", f"{len(rows)} rows parse as `unknown` (every one listed).", ""]
    return out + table(["battle", "turn#index", "reason", "text"],
                       [[r["battle"], f"T{r['turn']}#{r['index']}", cell(r["reason"]), cell(r["text"])] for r in rows])


def sprite_section(data: dict) -> list[str]:
    s = data["sprites"]
    total = sum(s["status_total"].values())
    out = ["## Sprites", "",
           "Each row may carry the row's sprite read from the log frame. Status totals: "
           + ", ".join(f"{k} {n} ({pct(n, total)})" for k, n in s["status_total"].items()) + ".", "",
           "Sprite record keys (no key gives the side):", ""]
    out += table(["keys", "rows"], [[cell(k), n] for k, n in s["record_keys"].items()])
    if s["reasons"]:
        out += ["Reasons on unmatched sprites: " + ", ".join(f"{k} {n}" for k, n in s["reasons"].items()) + ".", ""]
    out += ["### Match rate per kind", ""]
    statuses = list(s["status_total"])
    rows = []
    for kind, c in s["per_kind"].items():
        n = sum(c.values())
        rows.append([kind, n] + [c.get(st, 0) for st in statuses] + [pct(c.get("matched", 0), n)])
    out += table(["kind", "rows"] + statuses + ["matched %"], rows)
    out += ["### Sprite species vs the text name (matched rows)", "",
            "Agree = the text name (without 'The opposing') equals the sprite's base species or form, "
            "ignoring case and punctuation.", ""]
    out += table(["kind", "agree", "disagree", "no text name"],
                 [[k, c.get("agree", 0), c.get("disagree", 0), c.get("no text name", 0)]
                  for k, c in s["name_agreement"].items()])
    if s["disagreements"]:
        out += ["Every disagreement:", ""]
        out += table(["kind, text vs sprite", "rows"], [[cell(k), n] for k, n in s["disagreements"].items()])
    out += ["### Forms the sprite adds", "",
            f"{s['forms_rows']} of {s['matched_rows']} matched rows ({pct(s['forms_rows'], s['matched_rows'])}) "
            "have a sprite name that differs from its base species: the form the text does not give.", ""]
    return out + table(["base -> sprite form", "rows"], [[k, n] for k, n in s["forms"].items()])


def search_rows(searches: list[dict]) -> list[list]:
    return [[s["label"], cell(s["regex"]), s["scope"], s["count"], s["battles"]] for s in searches]


def matched_texts(searches: list[dict]) -> list[str]:
    out = []
    for s in searches:
        if not s["count"]:
            continue
        texts = list(s["texts"].items())
        more = f" (first {SHOWN_TEXTS} of {len(texts)} distinct; all in the JSON)" if len(texts) > SHOWN_TEXTS else ""
        kinds = ", ".join(f"{k} {n}" for k, n in s["by_kind"].items())
        out += [f"Texts matching '{s['label']}' (by kind: {kinds}){more}:", ""]
        out += [f"- {cell(t)} x{n}" for t, n in texts[:SHOWN_TEXTS]] + [""]
    return out


def shown_lines(shown: dict) -> list[str]:
    out = []
    for label, value in shown.items():
        if isinstance(value, dict):
            value = ", ".join(f"{k} {n}" for k, n in value.items()) or "none"
        out.append(f"- {label}: {value}")
    return out + [""] if out else []


def never_section(data: dict) -> list[str]:
    out = ["## What the game never shows", "",
           "Each item is checked by regex over the text of all recorded rows (Python `re.search`; the scope "
           "column says when only rows of one parsed kind were searched). Counts are rows and battles.", ""]
    for c in data["never_shown"]:
        out += [f"### {c['id']} {c['item']}", ""] + ([c["note"], ""] if c.get("note") else []) + ["Searched for:", ""]
        out += table(["search", "regex", "scope", "rows", "battles"], search_rows(c["searches"]))
        out += matched_texts(c["searches"])
        if c.get("shown_searches"):
            out += ["What is shown instead:", ""]
            out += table(["search", "regex", "scope", "rows", "battles"], search_rows(c["shown_searches"]))
            out += matched_texts(c["shown_searches"])
        if c.get("shown"):
            out += ["Related counts:", ""] + shown_lines(c["shown"])
    return out


def recorded_section(data: dict) -> list[str]:
    r = data["recorded_vs_today"]
    out = ["## Recorded decision records vs today's parser", "",
           f"For each of {r['battles_with_decisions']} battles with decision records, the last "
           "`decisions/NNNN-*.json` holds the translator's `unmapped` list for that battle. "
           f"{r['battles_with_unmapped']} battles have a non-empty list; {r['entries']} entries in all.", "",
           f"- Recorded `no_pattern`: {r['recorded_no_pattern']}. Today's parser, over all final rows: "
           f"{r['today_no_pattern_all_rows']} `no_pattern` "
           f"(all unknown reasons today: {', '.join(f'{k} {n}' for k, n in r['today_unknown_all_rows'].items())}).",
           "- Parser reasons come from the row parser (no_pattern, unreadable_*, mixed_hp_units, unsupported "
           "mechanic, ambiguous_template). Translator reasons are rows that parsed but could not be applied "
           "(unknown member, sprite not assignable, ...). Only parser entries can change with the parser.", "",
           "Entries by class (names and quoted values folded to 'X'):", ""]
    out += table(["class", "entries"], [[cell(k), n] for k, n in r["reason_classes"].items()])
    out += ["Every recorded reason:", ""]
    out += table(["reason", "entries"], [[cell(k), n] for k, n in r["recorded_reasons"].items()])
    still = r["parser_entries_still_unknown_today"]
    out += [f"Parser entries still unknown today: "
            + (", ".join(f"{k} {n}" for k, n in still.items()) or "none") + ".", ""]
    handled = r["parser_entries_handled_today"]
    out += [f"### Rows today's parser now handles ({len(handled)})", ""]
    return out + table(["battle", "row", "recorded reason", "today", "text"],
                       [[h["battle"], h["row"], cell(h["recorded"]), h["today"], cell(h["text"])] for h in handled])


def render(data: dict) -> str:
    out = head(data) + kinds_summary(data) + ["## Each kind", ""]
    for kind, v in data["kinds"].items():
        out += kind_section(kind, v)
    out += unknown_section(data) + sprite_section(data) + never_section(data) + recorded_section(data)
    return "\n".join(out).rstrip() + "\n"
