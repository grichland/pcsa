"""Deliverable A: every PL template -> the 0.2 kind and fields the converter sends, from templates.json.

Writes docs/investigation/cg-events/mapping-0.2.md and mapping-0.2.json.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import templates as tpl  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "docs" / "investigation" / "cg-events"
NOTES = {  # why a template is flagged, by problem code
    "missing:side": "the row's pill side was not read (no saved frame position)",
    "missing:stat": "one row names several stats; sent as `stats` (list)",
    "extra:stats": "one row names several stats; sent as `stats` (list)",
    "missing:form": "the row names the Mega without X/Y/Z; `form` left out (the mega_stone row names the stone)",
    "extra:effect": "Rest: status slp plus the wording id in `effect` (not a 0.2 field)",
    "extra:mon": "Sticky Web acted on a named Pokemon; `mon` is not a 0.2 field of `side`",
    "missing:mon": "names no Pokemon (Gem); `item` requires side and mon",
    "missing:type": "a type was lost (Burn Up, Double Shock); sent as `lose`, no new type is shown",
    "extra:lose": "a type was lost (Burn Up, Double Shock); sent as `lose`, no new type is shown",
}


# Wordings LIVE.md names that no recorded row shows: (template, a sample row to convert).
UNSEEN = [
    ("The opposing {MON} lost {N} PP from {MOVE}!", "The opposing Gengar lost 4 PP from Shadow Ball!"),
    ("{MON} lost {N} PP from {MOVE}!", "Gholdengo lost 3 PP from Make It Rain!"),
]


def unseen_rows() -> list[str]:
    from pcsa.events.live import convert_rows
    from pcsa.events.live_ids import Teams

    out = []
    for template, sample in UNSEEN:
        event = convert_rows([{"turn": 1, "index": 0, "text": sample}], Teams(own=()))[0][1]
        out.append(f"| `{cell(template)}` | `{cell(sample)}` | `{cell(json.dumps(event))}` |")
    return out


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def main() -> None:
    produced = json.loads((OUT / "templates.json").read_text(encoding="utf8"))
    rows, md = [], []
    for t in tpl.load():
        got = produced.get(t.id, {"rows": 0, "shapes": {}, "problems": {}, "example": None})
        shapes = got["shapes"]
        kinds = sorted({s.split("(")[0] for s in shapes})
        flags = []
        if not shapes:
            flags.append("no recorded row matched this template here")
        if len(kinds) > 1:
            flags.append("rows of this template map to several kinds: " + ", ".join(kinds))
        if "unread" in kinds:
            flags.append("some rows sent as unread")
        for p, n in got["problems"].items():
            flags.append(f"{p} x{n}: {NOTES.get(p, '')}".rstrip(": "))
        main_shape = max(shapes, key=shapes.get) if shapes else ""
        rows.append({"id": t.id, "cg_rows": t.rows, "rows_here": got["rows"], "class": t.cls, "category": t.category,
                     "template": t.text, "kind": kinds[0] if len(kinds) == 1 else kinds, "shapes": shapes,
                     "example_event": (got["example"] or {}).get("event"), "flags": flags})
        md.append(f"| {t.id} | {t.rows} | {got['rows']} | {t.cls} | {cell(t.category)} | `{cell(t.text)}` | "
                  f"`{cell(main_shape)}` | {cell('; '.join(flags))} |")
    (OUT / "mapping-0.2.json").write_text(json.dumps(rows, indent=1, ensure_ascii=False), encoding="utf8")
    head = ("| PL | CG rows | rows here | CG class | cat | template | 0.2 event sent (most common shape) | flags |\n"
            "|---|---|---|---|---|---|---|---|")
    (OUT / "mapping-0.2.md").write_text(
        "# PL templates to LIVE.md events\n\nGenerated by `tools/cg_events/mapping_table.py` from the converter's "
        "output on all 548 recorded battles. `rows here` is the rows this repo's matcher assigned to the template "
        "(most specific match); it can differ slightly from CG's count.\n\n" + head + "\n" + "\n".join(md) + "\n"
        "\n## Wordings named in LIVE.md but never recorded\n\nNo PL id: not in the 548 recorded battles. The "
        "template comes from the user; the event is what the converter sends for the sample row.\n\n"
        "| template | sample row | event sent |\n|---|---|---|\n" + "\n".join(unseen_rows()) + "\n",
        encoding="utf8")
    flagged = [r for r in rows if r["flags"]]
    print(len(rows), "templates;", len(flagged), "flagged")
    for r in flagged:
        print(r["id"], r["cg_rows"], r["rows_here"], r["template"][:60], "|", "; ".join(r["flags"])[:200])


if __name__ == "__main__":
    main()
